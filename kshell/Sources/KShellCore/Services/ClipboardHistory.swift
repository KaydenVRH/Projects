import AppKit

/// What's been copied lately, for the clipboard launcher.
///
/// Polls the pasteboard's change count (a cheap integer read) and records each
/// new piece of text. Anything a password manager marks as concealed or
/// transient is never recorded, and the history lives only in memory — copied
/// secrets never reach a file — so it starts empty with the shell.
public final class ClipboardHistory {
    public static let shared = ClipboardHistory()

    public struct Entry: Equatable {
        public let text: String
        public let copied: Date
        /// The app that was in front when it was copied.
        public let app: String?
    }

    public private(set) var entries: [Entry] = []

    /// Marker types from nspasteboard.org: a password, a one-off, or something
    /// generated that isn't the user's own copy.
    private static let skipped: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]
    private let limit = 80
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    public func start() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    public func stop() {
        timer?.invalidate()
        timer = nil
    }

    public func clear() {
        entries.removeAll()
    }

    /// Put an entry back on the pasteboard. The next poll sees it and moves it
    /// to the top, as if it had just been copied.
    public func copy(_ entry: Entry) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(entry.text, forType: .string)
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped),
              let text = board.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count < 256_000 else { return }
        let app = NSWorkspace.shared.frontmostApplication
        let own = app?.processIdentifier == ProcessInfo.processInfo.processIdentifier
        let previous = entries.first { $0.text == text }
        entries.removeAll { $0.text == text }
        // Copied back from the launcher: keep where it really came from.
        entries.insert(Entry(text: text, copied: Date(), app: own ? previous?.app : app?.localizedName), at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
    }
}
